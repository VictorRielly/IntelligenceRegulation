#!/usr/bin/env python3
"""D63 step L6 (2026-11-06): write axioms_l6.lean, a `#print axioms` line for EVERY theorem of the three L6 library files
(ExecMle.lean, ExecSumcheck.lean, ExecCfs.lean), qualified by the namespaces the file opens inside `ZK60.Exec`.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["ExecMle.lean", "ExecSumcheck.lean", "ExecCfs.lean"]
lines = ["import ZK60Formal.ExecSumcheck", "import ZK60Formal.ExecCfs", "",
         "-- D63 step L6 (2026-11-06): the axiom audit of the executable sumcheck verifier's theorems (generated by",
         "-- gen_axioms.py: every `theorem` of ExecMle.lean, ExecSumcheck.lean and ExecCfs.lean). Each must show at most",
         "-- `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).", ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = ".".join(stack + [m.group(1)])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
