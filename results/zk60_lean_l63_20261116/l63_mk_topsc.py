def rep(t, old, new, n=1):
    assert t.count(old) == n, (t.count(old), n, old[:100])
    return t.replace(old, new)


def tok_end(s, i, count):
    """index after `count` top-level tokens from i; returns list of (a, b)"""
    out = []
    while len(out) < count:
        while s[i].isspace():
            i += 1
        j, d = i, 0
        while j < len(s):
            c = s[j]
            if c in "([{":
                d += 1
            elif c in ")]}":
                if d == 0:
                    break
                d -= 1
            elif c.isspace() and d == 0:
                break
            j += 1
        out.append((i, j))
        i = j
    return out


def call_span(s, name, nargs):
    a = s.index(name)
    assert s.count(name) == 1, (s.count(name), name[:60])
    toks = tok_end(s, a + len(name.split(" ")[0]) + 1, nargs)
    return a, toks


