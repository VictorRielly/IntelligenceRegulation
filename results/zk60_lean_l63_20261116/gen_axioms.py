lines = ["import ZK60Formal.RunStgShieldIncBT", "import ZK60Formal.RunStgShieldInXEp", "import ZK60Formal.RunStgShieldOutNum", "import ZK60Formal.RunStgShieldTopL", "import ZK60Formal.RunStgShieldIncAt", "import ZK60Formal.RunStgShieldIncJoin", "import ZK60Formal.RunStgShieldIncCube", "import ZK60Formal.RunStgShieldIncRun", "import ZK60Formal.RunStgShieldTopI", "import ZK60Formal.RunStgShieldCTopI", "import ZK60Formal.RunStgShieldCTopF", "import ZK60Formal.RunStgShieldCTopW", "import ZK60Formal.RunStgShieldTopDz", "import ZK60Formal.RunStgShieldTopPd", "import ZK60Formal.RunStgShieldIncSem", "import ZK60Formal.RunStgShieldTopIO", "import ZK60Formal.RunStgShieldTopTrI", "import ZK60Formal.RunStgShieldTopTrO", "import ZK60Formal.RunStgShieldTopSJ", "import ZK60Formal.RunStgShieldTopBx", "import ZK60Formal.RunStgShieldRbr","",
         "-- D63 lane L63 (2026-11-16): the audit of the stages' define polynomials (generated by gen_axioms.py: every",
         "-- `theorem`, `def`, `abbrev` and `structure` of the four library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
counts = {}
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^(?:noncomputable )?(theorem|def|abbrev|structure) (\S+)", raw)
        if m:
            kind, name = m.group(1), m.group(2)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            counts[kind] = counts.get(kind, 0) + 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{sum(counts.values())} declarations: " + ", ".join(f"{counts[k]} {k}" for k in sorted(counts)))
