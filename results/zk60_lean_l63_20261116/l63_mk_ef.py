def balanced(s, i):
    """s[i] == '(' ; index just after the matching ')'"""
    d = 0
    for j in range(i, len(s)):
        if s[j] == "(":
            d += 1
        elif s[j] == ")":
            d -= 1
            if d == 0:
                return j + 1
    raise ValueError("unbalanced")


def one(txt, pat):
    assert txt.count(pat) == 1, (pat, txt.count(pat))
    return txt.find(pat)


def subst_fold(txt):
    """every occurrence of the variable `embFold` (a whole word) becomes the concrete fold"""
    return re.sub(r"(?<![\w.])embFold(?![\w'])", FOLD, txt)


