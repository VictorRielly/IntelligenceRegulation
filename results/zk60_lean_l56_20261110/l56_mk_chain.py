#!/usr/bin/env python3
"""D63 lane L56 (2026-11-10): generate formal/ZK60Formal/RunBndChain.lean, the app's top-theorem chain with the block
slots' polynomial type widened (finding L54-1's repair): lane L52's three top theorems
  eb_productionReadyL_epP_exec_alive (RunEpBChain.lean, section EbRaTop),
  eb_productionReadyL_epP_code       (RunEpBTop.lean,   section EbCodeTop),
  eb_productionReadyL_epP_codeT      (RunEpBTopT.lean,  section EbCodeTTop),
restated, so that every discharge of lanes L50 and L52 is kept. Changes, each asserted to apply exactly once per
section:
  * the name `eb_…` -> `bnd_…`, the section `Eb…` -> `Bnd…`, the call to the previous theorem of the chain likewise;
  * the binder `Fsl`: its type gets the header's roots and cuts `Exec.Block.HdrX Lq` after the roots (lane L56's
    `blockSlotXB`);
  * `hslB`: `blockSchedX` -> `blockSchedXB` (the same arguments);
  * `hsl_blk`: `RaTermAt` -> `RaTermAtB` (the same arguments);
  * in `exec_alive`'s proof: `ra_hal_sl` -> `ra_hal_slB` (the same named arguments).
Every other binder and every proof step is the original's text.
usage: python3 l56_mk_chain.py <WT>
"""
import sys

WT = sys.argv[1] if len(sys.argv) > 1 else "."
L = WT + "/formal/ZK60Formal/"


def once(text, old, new):
    n = text.count(old)
    assert n == 1, (old[:100], n)
    return text.replace(old, new)


def section(fname, name):
    src = open(L + fname).read()
    i = src.index("section %s\n" % name)
    j = src.index("end %s\n" % name, i) + len("end %s\n" % name)
    return src[i:j]


FSL_OLD = ("(Fsl : (k : ℕ) → Exec.Block.Cuts3 Lq → Exec.Block.RootsO → (j : ℕ) → Exec.Block.Seen →")
FSL_NEW = ("(Fsl : (k : ℕ) → Exec.Block.Cuts3 Lq → Exec.Block.RootsO → Exec.Block.HdrX Lq → (j : ℕ) →\n"
           "      Exec.Block.Seen →")
SL_OLD = "D.sls (k + 1) = Exec.Block.blockSchedX (Pk k)"
SL_NEW = "D.sls (k + 1) = Exec.Block.blockSchedXB (Pk k)"
TM_OLD = "∀ k, k < Lb → RaTermAt U key domain (Pk k)"
TM_NEW = "∀ k, k < Lb → RaTermAtB U key domain (Pk k)"

PRE = ("**L56 (finding L54-1's repair: every block slot's polynomial `Fsl k` also receives the header's roots and cuts\n"
       "`hdrX`, so the two boundary slots' polynomials are of its type; the schedule is `blockSchedXB`, the terminal\n"
       "identity `RaTermAtB`) of `%s`.** ")

specs = [
    ("RunEpBChain.lean", "EbRaTop", "BndRaTop", "eb_productionReadyL_epP_exec_alive", "bnd_productionReadyL_epP_exec_alive",
     None),
    ("RunEpBTop.lean", "EbCodeTop", "BndCodeTop", "eb_productionReadyL_epP_code", "bnd_productionReadyL_epP_code",
     ("eb_productionReadyL_epP_exec_alive", "bnd_productionReadyL_epP_exec_alive")),
    ("RunEpBTopT.lean", "EbCodeTTop", "BndCodeTTop", "eb_productionReadyL_epP_codeT", "bnd_productionReadyL_epP_codeT",
     ("eb_productionReadyL_epP_code", "bnd_productionReadyL_epP_code")),
]

outs = []
for (fname, sec0, sec1, th0, th1, call) in specs:
    s = section(fname, sec0)
    s = once(s, "section %s\n" % sec0, "section %s\n" % sec1)
    s = once(s, "end %s\n" % sec0, "end %s\n" % sec1)
    t = s.index("theorem %s " % th0)
    d = s.rindex("/-- ", 0, t)
    assert s[d:t].count("-/") == 1, fname
    s = s[:d] + "/-- " + (PRE % th0) + s[d + len("/-- "):]
    s = once(s, "theorem %s " % th0, "theorem %s " % th1)
    if call is not None:
        s = once(s, "exact %s (" % call[0], "exact %s (" % call[1])
    s = once(s, FSL_OLD, FSL_NEW)
    s = once(s, SL_OLD, SL_NEW)
    s = once(s, TM_OLD, TM_NEW)
    if call is None:
        s = once(s, "ZK60.ProtocolClassify.ra_hal_sl (U := U)", "ZK60.ProtocolClassify.ra_hal_slB (U := U)")
    assert "RaTermAt " not in s.replace("RaTermAtB ", ""), fname
    assert "blockSchedX " not in s, fname
    outs.append(s)

HEAD = """/-
D63 lane L56 (2026-11-10), part 4: **the app's top-theorem chain with the block slots' polynomials widened** (finding
L54-1's repair). GENERATED by `results/zk60_lean_l56_20261110/l56_mk_chain.py` from lane L52's
`eb_productionReadyL_epP_exec_alive` (RunEpBChain.lean), `eb_productionReadyL_epP_code` (RunEpBTop.lean) and
`eb_productionReadyL_epP_codeT` (RunEpBTopT.lean). The proofs are the originals' steps.

What changes, in every theorem: the block slots' polynomial `Fsl k` also receives the header's roots and cuts
(`Exec.Block.HdrX Lq`, lane L56's `hdrX`: every root the run's transcript absorbed before the block's own roots, and
the prover's log cut at each, the block's input and output boundary roots among them); the kinds data's block slots are
`blockSchedXB` (`hslB`); the slots' terminal identity is `RaTermAtB` (`hsl_blk`); `hal_slots` is lane L56's
`ra_hal_slB`.

* **`bnd_productionReadyL_epP_exec_alive`**, **`bnd_productionReadyL_epP_code`**,
  **`bnd_productionReadyL_epP_codeT`**: lane L52's three, so restated.

Only `propext`, `Classical.choice`, `Quot.sound`.
-/
import ZK60Formal.RunEpBTopT
import ZK60Formal.RunBndHal

set_option autoImplicit false
set_option linter.constructorNameAsVariable false

namespace ZK60.ProtocolClassify.RunShapeP

open scoped ENNReal
open ZK60 ZK60.Exec ZK60.TokenRun ZK60.Sound ZK60.Assembly ZK60.StageX ZK60.Exec.Link Code ZK60.RunShape
open ZK60.Exec.StageV (IncV OutcV StageGeom classifyRunV classifyProtocolExec)
open ZK60.Circuit (gP GF)
open ZK60.Block (BlockShape BlockPublic BlockSat)
open ZK60.D76 (LeaksAtMost productionReadyL_of_productionReady productionReadyL_of_productionReady_range)
open ZK60.ProtocolClassify (ebData EbXW abRdIn eb_hal_opB eb_hal_M eb_bud_r13)
open ZK60.ProtocolClassify (ClsHdrW clsHdrOf clsStart)

"""
out = HEAD + "\n".join(outs) + "\nend ZK60.ProtocolClassify.RunShapeP\n"
open(L + "RunBndChain.lean", "w").write(out)
print("RunBndChain.lean: %d lines" % out.count("\n"))
