KINDS = [("rtKB", "hal_opB"), ("rtKM", "hal_M"), ("rtKA", "hal_opA"), ("rtKsl", "hal_slots"), ("rtKR0", "hal_R0"),
         ("rtKR1", "hal_R1"), ("rtKH0", "hal_H0"), ("rtKH1", "hal_H1"), ("rtKLU", "hal_LU")]
