def top_split(some_text):
    """`rc_productionReady_r13_top`: `rc_productionReady_r13_some` with `halive` replaced by nine premises, one per
    kind of `rtKo`, each conditional on the earlier kinds having no doomed entrant (`rc_aliveOrd9`)."""
    s = some_text
    i = s.index("    (halive :")
    j = s.index("    (hdin :")
    hal = s[i:j].rstrip("\n").split("\n")
    head = hal[:3]  # the binder's quantifiers, the acceptance, the extraction failure
    binders = []
    for n, (k, h) in enumerate(KINDS):
        pre = [f"      ¬ ({KINDS[m][0]} {KARGS}).Dm {NLT} →" for m in range(n)]
        hd = [head[0].replace("(halive :", f"({h} :")] + head[1:]
        binders += hd + pre + [f"      ({k} {KARGS}).Al {NLT})"]
    s = s[:i] + "\n".join(binders) + "\n" + s[j:]
    s = s.replace("theorem rc_productionReady_r13_some", "theorem rc_productionReady_r13_top", 1)
    k = s.index("εcTarget εsTarget εsTarget εzkTarget :=")
    s = s[:k] + "εcTarget εsTarget εsTarget εzkTarget :=\n"
    s += (f"  rc_productionReady_r13_some {TOPARGS}\n"
          "    (fun A G hv' hx' => rc_aliveOrd9 _ _ _ _ _ _ _ _ _ _ _ _ "
          + " ".join(f"({h} A G hv' hx')" for _, h in KINDS) + ")\n"
          "    hdin hdblk hdout mk ops hE hops hcan hwin hread hBal hdzero hzk")
    return s


