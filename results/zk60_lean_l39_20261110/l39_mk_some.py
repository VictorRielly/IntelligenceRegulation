ug = lines_of("RunChainUGate.lean")
ut = lines_of("RunChainUToken.lean")
tg = lines_of("RunTrGate.lean")


def block(lines, start_pat, stop_pat):
    i = next(k for k, l in enumerate(lines) if re.match(start_pat, l))
    j = next(k for k in range(i, len(lines)) if re.match(stop_pat, lines[k]))
    return lines[i:j]


# the section headers (variables and local notations), copied
gen_vars = block(ug, r"^section Generic", r"^/--")
gate_vars = block(ug, r"^section Gates", r"^/--")
tok_vars = block(ut, r"^section TokenR13", r"^/--")
top_vars = block(tg, r"^section GateR13", r"^/--")

