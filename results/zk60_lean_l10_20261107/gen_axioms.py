#!/usr/bin/env python3
"""D63 lane L10 (2026-11-07): write axioms_l10.lean, a `#print axioms` line for EVERY theorem of the L10 library files,
qualified by the namespaces each file opens. A copy of results/zk60_lean_l8_20261106/gen_axioms.py with this lane's
files (the checker ExecOpeningCheck.lean defines `main` and holds no theorem).

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["ExecOpeningCode.lean", "BindingW16.lean", "ExecOpening.lean", "ExecOpeningM.lean", "ExecOpeningFS.lean"]
lines = ["import ZK60Formal.BindingW16", "import ZK60Formal.ExecOpeningFS", "",
         "-- D63 lane L10 (2026-11-07): the axiom audit of the W16R2 opening checks, M's test, the L8-5 transfer,",
         "-- M under Fiat-Shamir and Binding (generated by gen_axioms.py: every `theorem` of the five library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = m.group(1)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
