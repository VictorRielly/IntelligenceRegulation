#!/usr/bin/env python3
"""D63 lane L26 (2026-11-07): write axioms_l26.lean, a `#print axioms` line for EVERY theorem, definition, abbreviation
and structure of the L26 library files, qualified by the namespaces each file opens. From
results/zk60_lean_l24_20261107/gen_axioms.py, with this lane's files; it also audits the definitions (the instance
`classifyProtocolU` is one), which L24's copy did not.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["BindingU.lean", "BindingUTest.lean", "BindingUDecode.lean", "ProtocolClassifyU.lean",
         "ProtocolClassifyUEp.lean"]
lines = ["import ZK60Formal.ProtocolClassifyUEp", "",
         "-- D63 lane L26 (2026-11-07): the audit of the unique-decoding opening, its binding and O11d (generated by",
         "-- gen_axioms.py: every `theorem`, `def`, `abbrev` and `structure` of the five library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
counts = {}
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^(?:noncomputable )?(theorem|def|abbrev|structure) (\S+)", raw)
        if m:
            kind, name = m.group(1), m.group(2)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            counts[kind] = counts.get(kind, 0) + 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{sum(counts.values())} declarations: " + ", ".join(f"{counts[k]} {k}" for k in sorted(counts)))
