#!/usr/bin/env python3
"""D63 lane L23 (2026-11-07): write axioms_l23.lean, a `#print axioms` line for EVERY theorem of the L23 library files,
qualified by the namespaces each file opens. A copy of results/zk60_lean_l21_20261107/gen_axioms.py with this lane's
files.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["CoverW16.lean", "CoverW16Unmask.lean", "CoverW16Target.lean", "CoverW16Gen.lean", "CoverW16Inst.lean",
         "CoverW16R13.lean", "CoverW16Shapes.lean", "SlotPolyW16Kinds.lean", "SlotPolyW16.lean", "SlotPolyW16Draw.lean", "SlotPolyW16Map.lean", "SlotPolyW16Seg.lean"]
lines = ["import ZK60Formal.CoverW16R13", "import ZK60Formal.CoverW16Shapes", "import ZK60Formal.SlotPolyW16Map", "import ZK60Formal.SlotPolyW16Seg", "",
         "-- D63 lane L23 (2026-11-07): the axiom audit of the W16R2 / R13 instance lane (generated by",
         "-- gen_axioms.py: every `theorem` of the twelve library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = m.group(1)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
