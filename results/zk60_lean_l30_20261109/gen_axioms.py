#!/usr/bin/env python3
"""D63 lane L30 (2026-11-09): write axioms_l30.lean, a `#print axioms` line for EVERY theorem, definition, abbreviation
and structure of the L30 library files, qualified by the namespaces each file opens. From
results/zk60_lean_l26_20261107/gen_axioms.py, with this lane's files; a declaration may carry an attribute
(`@[reducible] def …`).

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["BindingUCode.lean", "RunChainUOrd.lean", "RunChainUStab.lean", "RunChainUGate.lean", "RunChainUExec.lean",
         "RunChainUToken.lean"]
lines = ["import ZK60Formal.RunChainUExec", "import ZK60Formal.RunChainUToken", "",
         "-- D63 lane L30 (2026-11-09): the audit of the gate at `classifyProtocolU` through the run's chain, the",
         "-- column test on the run's transcript and finding L26-3's code fact (generated by gen_axioms.py: every",
         "-- `theorem`, `def`, `abbrev` and `structure` of the six library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
counts = {}
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}", encoding="utf-8"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^(?:@\[[^\]]*\]\s*)?(?:noncomputable )?(theorem|def|abbrev|structure) (\S+)", raw)
        if m:
            kind, name = m.group(1), m.group(2)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            counts[kind] = counts.get(kind, 0) + 1
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{sum(counts.values())} declarations: " + ", ".join(f"{counts[k]} {k}" for k in sorted(counts)))
