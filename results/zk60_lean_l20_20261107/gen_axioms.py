#!/usr/bin/env python3
"""D63 lane L20 (2026-11-07): write axioms_l20.lean, a `#print axioms` line for EVERY theorem of the L20 library files,
qualified by the namespaces each file opens. A copy of results/zk60_lean_l16_20261107/gen_axioms.py with this lane's
files.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["CountW16Chain.lean", "CountW16Slots.lean", "CountW16Target.lean", "OpenKnowChain.lean",
         "OpenKnowBlock.lean"]
lines = ["import ZK60Formal.OpenKnowBlock", "",
         "-- D63 lane L20 (2026-11-07): the axiom audit of the per-position count and the openings' knowledge",
         "-- (generated by gen_axioms.py: every `theorem` of the L20 library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = m.group(1)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
