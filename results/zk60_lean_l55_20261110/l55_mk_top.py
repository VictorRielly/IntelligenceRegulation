print("RunVerdictTop.lean:", out.count("\n"), "lines;", len(explicit0), "explicit binders of L52's theorem;",
      len(explicit1), "of the new one; gone:", sorted(set(explicit0) - set(explicit1)), "new:",
      sorted(set(explicit1) - set(explicit0)), "; Win replaced", nwin, "times, Wout", nwout)
