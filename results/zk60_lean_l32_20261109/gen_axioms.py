#!/usr/bin/env python3
"""D63 lane L32 (2026-11-09): write axioms_l32.lean, a `#print axioms` line for EVERY theorem, definition, abbreviation
and structure of the L32 library files, qualified by the namespaces each file opens. From
results/zk60_lean_l26_20261107/gen_axioms.py, with this lane's files.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["HonestOpenPcs.lean", "HonestOpenM.lean", "HonestOpenFields.lean", "HonestOpenSites.lean",
         "HonestRunBlock.lean", "HonestRunProg.lean", "HonestRunCount.lean", "HonestRunCover.lean",
         "HonestRunStageIn.lean", "HonestRunStageOut.lean"]
lines = ["import ZK60Formal.HonestRunBlock", "import ZK60Formal.HonestRunProg", "import ZK60Formal.HonestRunCover",
         "import ZK60Formal.HonestRunStageIn", "import ZK60Formal.HonestRunStageOut", "",
         "-- D63 lane L32 (2026-11-09): the audit of the openings' honest provers and completeness, check_opening's",
         "-- sites, a block core from its tables, the openings as transcript programs and the counts (generated by",
         "-- gen_axioms.py: every `theorem`, `def`, `abbrev` and `structure` of the ten library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
counts = {}
per_file = {}
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^(?:noncomputable )?(theorem|def|abbrev|structure) (\S+)", raw)
        if m:
            kind, name = m.group(1), m.group(2)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            counts[kind] = counts.get(kind, 0) + 1
            per_file.setdefault(f, {})[kind] = per_file.setdefault(f, {}).get(kind, 0) + 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{sum(counts.values())} declarations: " + ", ".join(f"{counts[k]} {k}" for k in sorted(counts)))
for f in files:
    d = per_file.get(f, {})
    print(f"  {f}: " + ", ".join(f"{d[k]} {k}" for k in sorted(d)))
