#!/usr/bin/env python3
"""D63 lane L58 (2026-11-10): generate formal/ZK60Formal/RunEpXTopH.lean, the app's top theorem at the input
endpoint's real opening data (the brief's deliverable 2: `mk`, `hE`), from `ex_productionReadyL_epP_codeG`
(RunEpXTopG.lean). Changes, each asserted:
  * the name -> `ex_productionReadyL_epP_codeH`, the section -> `ExCodeHTop`;
  * the opening-data type is the code's (`Salt := EpxSalt Rr`: every row's words, pads, every column's salt and path;
    RunEpXMk.lean), with `msg := epxMsg …`, `pad`, `salt`, `path` its fields, and `msg_place` PROVED from one new
    premise `hplace : Function.Injective place` (the data rows sit at distinct rows; one data row at the code's
    geometry);
  * `mk := epxMk …` (PROVED: a `SaltMk` at that type);
  * `E := epxE (CinR) mk pos ops E0` (its `epW` and `r` read from `ops`; `E0` gives the other fields) and `hE` PROVED
    (`epxE_hE`, by definition);
  * the proof: `ex_productionReadyL_epP_codeG` with every binder passed by name.
usage: python3 l58_mk_topH.py <WT>
"""
import re
import sys

WT = sys.argv[1] if len(sys.argv) > 1 else "."
L = WT + "/formal/ZK60Formal/"
src = open(L + "RunEpXTopG.lean").read()
i = src.index("section ExCodeGTop\n")
j = src.index("end ExCodeGTop\n", i) + len("end ExCodeGTop\n")
sec = src[i:j]
END_TOK = "(classifyLeakP Rp) εcTarget εsTarget εsTarget εzkTarget :="


def once(text, old, new):
    n = text.count(old)
    assert n == 1, (old[:90], n)
    return text.replace(old, new)


def cut(text, start, stop):
    a = text.index(start)
    assert text.count(start) == 1, start[:60]
    b = text.index(stop, a)
    return text[a:b]


def top_binders(text):
    i = text.index(" ") + 1
    i = text.index(" ", i)
    out = []
    depth = 0
    start = None
    opener = None
    pairs = {"(": ")", "{": "}", "[": "]", "⦃": "⦄"}
    closers = set(pairs.values())
    while i < len(text):
        c = text[i]
        if depth == 0 and c == ":" and text[i:i + 2] == ":=":
            break
        if depth == 0 and c == ":" and opener is None:
            break
        if c in pairs:
            if depth == 0:
                start = i
                opener = c
            depth += 1
        elif c in closers:
            depth -= 1
            if depth == 0 and opener is not None:
                grp = text[start:i + 1]
                inner = grp[1:-1]
                names = []
                if opener in "({" and ":" in inner:
                    names = inner[:inner.index(":")].split()
                out.append((opener, names, start, i + 1))
                opener = None
        i += 1
    return out


th0 = sec.index("theorem ex_productionReadyL_epP_codeG ")
th1 = sec.index(END_TOK, th0) + len(END_TOK)
explicit0 = [n for (k, ns, _, _) in top_binders(sec[th0:th1]) if k == "(" for n in ns]
for n in ["E", "mk", "hE"]:
    assert n in explicit0, n

sec = once(sec, "section ExCodeGTop\n", "section ExCodeHTop\n")
sec = once(sec, "end ExCodeGTop\n", "end ExCodeHTop\n")
sec = once(sec, "theorem ex_productionReadyL_epP_codeG ", "theorem ex_productionReadyL_epP_codeH ")
t = sec.index("theorem ex_productionReadyL_epP_codeH ")
d = sec.rindex("/-- ", 0, t)
sec = sec[:d] + (
    "/-- **THE APP'S TOP THEOREM AT THE INPUT ENDPOINT'S REAL OPENING DATA** (D63 lane L58). `ex_productionReadyL_epP_codeG`\n"
    "with the input commitment's opening data the code's (`EpxSalt Rr`: rows' words, pads, salts, paths; `msg := epxMsg …`,\n"
    "`msg_place` from `hplace`), `mk := epxMk …` and `E := epxE … E0` (its input endpoint words and opening data read from\n"
    "`ops`), so `mk` and `hE` are gone. Generated by `results/zk60_lean_l58_20261110/l58_mk_topH.py`.\n-/\n") + sec[t:]

SALT = "(ZK60.ProtocolClassify.EpxSalt Rr)"
MSG = "(ZK60.ProtocolClassify.epxMsg Rr dR place pos)"
MSGP = "(ZK60.ProtocolClassify.epxMsg_place Rr dR place pos hplace)"
MK = "(ZK60.ProtocolClassify.epxMk Rr dR place hpos hplace ClsStmt.inRoot tag)"
OPS = "(ZK60.ProtocolClassify.epxOps tag Lq h64 key domain hs hL abRdIn 11 Rr (N := 2 ^ 11))"
EX = f"(ZK60.ProtocolClassify.epxE (CinR) {MK} pos {OPS} E0)"

sec = once(sec, "variable {S : BlockShape} {Hdr Salt Coins : Type}\n", "variable {S : BlockShape} {Hdr Coins : Type}\n")
sec = once(sec,
           "  (place : Fin dR → Fin Rr) (msg : (S.Tok → ℕ) → Salt → Fin Rr → Fin (2 ^ 8) → GF)\n"
           "  (msg_place : ∀ v r k, msg v r (place k) = posPlane pos v k) (pad : Salt → Fin Rr → Fin 256 → GF)\n"
           "  (salt : Salt → Fin (2 ^ 11) → Dig) (path : Salt → Fin (2 ^ 11) → List Dig) (tag : MTag)\n",
           "  (place : Fin dR → Fin Rr) (hplace : Function.Injective place) (tag : MTag)\n")
sec = once(sec, "  epTokenCommit (St := ClsStmt Hdr) Rr dR hpos place msg msg_place pad salt path ClsStmt.inRoot tag\n",
           "  epTokenCommit (St := ClsStmt Hdr) Rr dR hpos place " + MSG + "\n    " + MSGP
           + " ZK60.ProtocolClassify.EpxSalt.pads\n    ZK60.ProtocolClassify.EpxSalt.salts ZK60.ProtocolClassify.EpxSalt.paths"
           " ClsStmt.inRoot tag\n")
sec = once(sec, "    (E : List (QB Lq × Dig) → ClsStmt Hdr → ClsReceipt → RunExt S Salt)\n",
           "    (E0 : List (QB Lq × Dig) → ClsStmt Hdr → ClsReceipt → RunExt S " + SALT + ")\n")
sec = once(sec, "    (mk : (CinR).SaltMk)\n", "")
b_hE = cut(sec, "    (hE : ∀ lg s pf", "    (hdzero : ∀ (A : OC")
sec = once(sec, b_hE, "")

st_a = sec.index("theorem ex_productionReadyL_epP_codeH ")
st_b = sec.index(END_TOK, st_a)
stmt = sec[st_a:st_b]
n_E = len(re.findall(r"\bE\b", stmt))
stmt = re.sub(r"\bE\b", EX, stmt)
assert not re.search(r"\bSalt\b", stmt), "Salt left"
assert not re.search(r"\bmk\b", stmt), "mk left"
sec = sec[:st_a] + stmt + sec[st_b:]

SECVARS = ["Rr", "dR", "hpos", "place"]
fixed = {"E": EX, "mk": MK, "hE": "(ZK60.ProtocolClassify.epxE_hE (CinR) " + MK + " pos " + OPS + " E0)"}
args = [f"({n} := {n})" for n in SECVARS] + [f"(msg := {MSG})", f"(msg_place := {MSGP})",
                                            "(pad := ZK60.ProtocolClassify.EpxSalt.pads)",
                                            "(salt := ZK60.ProtocolClassify.EpxSalt.salts)",
                                            "(path := ZK60.ProtocolClassify.EpxSalt.paths)", "(tag := tag)"]
for n in explicit0:
    if n == "tag":
        continue
    args.append(f"({n} := {fixed.get(n, n)})")
lines = []
cur = "  exact ex_productionReadyL_epP_codeG"
for a in args:
    if len(cur) + 1 + len(a) > 118:
        lines.append(cur)
        cur = "    " + a
    else:
        cur += " " + a
lines.append(cur)
proof = "  by\n" + "\n".join(lines) + "\n"
p0 = sec.index("  by\n", sec.index(END_TOK))
p1 = sec.index("\nend ExCodeHTop\n")
sec = sec[:p0] + proof + sec[p1:]

header = '''/-
D63 lane L58 (2026-11-10), part 12: **the app's top theorem at the input endpoint's real opening data** (the brief's
deliverable 2: `mk`, `hE`). GENERATED by `results/zk60_lean_l58_20261110/l58_mk_topH.py` from
`ex_productionReadyL_epP_codeG` (RunEpXTopG.lean), so every earlier discharge is kept.

* **`ex_productionReadyL_epP_codeH`**: the opening data `EpxSalt Rr`, `mk := epxMk …`, `E := epxE … E0`; `mk`, `hE` and
  `msg_place` PROVED; one new premise `hplace` (the data rows' places are distinct).

Only `propext`, `Classical.choice`, `Quot.sound`.
-/
import ZK60Formal.RunEpXTopG
import ZK60Formal.RunEpXMk

set_option autoImplicit false
set_option linter.constructorNameAsVariable false

namespace ZK60.ProtocolClassify.RunShapeP

open scoped ENNReal
open ZK60 ZK60.Exec ZK60.TokenRun ZK60.Sound ZK60.Assembly ZK60.StageX ZK60.Exec.Link Code ZK60.RunShape
open ZK60.Exec.StageV (IncV OutcV StageGeom classifyRunV classifyProtocolExec)
open ZK60.Circuit (gP GF)
open ZK60.Block (BlockShape BlockPublic BlockSat)
open ZK60.D76 (LeaksAtMost productionReadyL_of_productionReady productionReadyL_of_productionReady_range)
open ZK60.ProtocolClassify (ClsHdrW clsHdrOf clsStart)

'''
out = header + sec + "\nend ZK60.ProtocolClassify.RunShapeP\n"
open(L + "RunEpXTopH.lean", "w").write(out)
print("RunEpXTopH.lean:", out.count("\n"), "lines;", len(explicit0), "explicit binders of codeG;", n_E,
      "uses of E replaced;", len(args), "named arguments")
