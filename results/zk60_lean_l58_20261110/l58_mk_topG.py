b_ops = cut(sec, "    (ops : List (QB Lq × Dig)", "    (hE : ∀ lg s pf")
sec = once(sec, b_ops, "")
b_hops = cut(sec, "    (hops : ∀ (A : OC", "    (hcan : ∀ lg s j o")
sec = once(sec, b_hops, "")
b_hcan = cut(sec, "    (hcan : ∀ lg s j o", "    (hread : ∀ (A : OC")
sec = once(sec, b_hcan, "")
