"""Generate token_io/r0_words.rs: R0's synthetic model words (r0/vectors.json) as Rust constants.

R0 (results/zk60_token_io_design_20261017/r0/vectors.json) stores its synthetic model's words so R1
can consume them without Python. This writes them, with R0's own SHA-256 digests (int16 LE / int8),
which the Rust test recomputes. Public synthetic data only. One thread, < 1 s.
"""
import hashlib
import json
import struct
import sys

SRC = "/home/victor/IntelligenceRegulation/results/zk60_token_io_design_20261017/r0/vectors.json"
DST = "/home/victor/IntelligenceRegulation/ops/zkp-mvp/token-io/hashline/src/private_block/token_io/r0_words.rs"

raw = open(SRC, "rb").read()
v = json.loads(raw)
m = v["model"]
E = [x for r in m["embedding"] for x in r]
W = [x for r in m["head"] for x in r]
assert hashlib.sha256(struct.pack("<%dh" % len(E), *E)).hexdigest() == m["embedding_sha256_i16"]
assert hashlib.sha256(struct.pack("<%db" % len(W), *W)).hexdigest() == m["head_sha256_i8"]
toks = v["vectors"]["V01_honest_public_row"]["tokens"]


def arr(xs, per=24):
    lines = []
    for i in range(0, len(xs), per):
        lines.append("    " + ", ".join(str(x) for x in xs[i:i + per]) + ",")
    return "\n".join(lines)


out = f"""//! GENERATED by `results/zk60_token_io_r1_20261017/tools/gen_r0_words.py` from rung R0's
//! `r0/vectors.json` (file sha256 {hashlib.sha256(raw).hexdigest()}): R0's deterministic
//! synthetic model (V = {m['V']}, d = {m['d']}, dense int16 embedding with distinct rows, dense int8
//! head), its BOS and pad ids, and the tokens of R0 vector V01. Public synthetic data only.

pub(crate) const R0_V: usize = {m['V']};
pub(crate) const R0_D: usize = {m['d']};
pub(crate) const R0_BOS: u64 = {m['bos']};
pub(crate) const R0_PAD_ID: u64 = {m['pad_id']};
/// R0's own digests: SHA-256 of the int16 little-endian / int8 words
pub(crate) const R0_EMB_SHA256_I16: &str = "{m['embedding_sha256_i16']}";
pub(crate) const R0_HEAD_SHA256_I8: &str = "{m['head_sha256_i8']}";
pub(crate) const R0_V01_TOKENS: [u64; {len(toks)}] = {toks};
#[rustfmt::skip]
pub(crate) const R0_EMB: [i16; {len(E)}] = [
{arr(E)}
];
#[rustfmt::skip]
pub(crate) const R0_HEAD: [i8; {len(W)}] = [
{arr(W)}
];
"""
open(DST, "w").write(out)
print("wrote", DST, len(out), "bytes; V01 tokens", toks)
