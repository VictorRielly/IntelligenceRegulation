#!/usr/bin/env python3
"""D63 lane L48 (2026-11-10): generate formal/ZK60Formal/RunOpenGeoTop.lean from lane L45's generated
RunExtractTop.lean: the app's top theorem with the two stages' `A` and `H` at the tier's REAL stage geometry
(`ogStage`: `2^12` columns, rate `1/4`), finding L45-2.

Substitutions (each counted, the script fails if a count differs from the expected one):
  * the stages' opening premises `RkPcsR13 U tag Iin.pA` (…`Iin.pH`, `Oout.pA`, `Oout.pH`) -> `RkPcsAt U tag ogStage …`;
  * the stages' run data `rxDin (RtRun.pf Rn)` / `rxDout (RtRun.pf Rn)` -> `rxDinG ogStage …` / `rxDoutG ogStage …`;
  * the proof's `rx_parts_AH` / `rx_parts_M` -> `rx_parts_AHG` / `rx_parts_MG` at `ogStage` (`ogStage_ok`, `Q = 256`);
  * the theorem's name and doc, the section name, the imports.
The blocks keep `RkPcsR13` (their geometry is the block geometry `2^14`, legitimately).

usage: python3 l48_mk_top.py <WT>
"""
import sys

WT = sys.argv[1] if len(sys.argv) > 1 else "."
src = open(WT + "/formal/ZK60Formal/RunExtractTop.lean").read()

HEAD_OLD_END = "-/\nimport ZK60Formal.RunCoverPRk\nimport ZK60Formal.RunExtractParts\n"
assert HEAD_OLD_END in src
body = src[src.index(HEAD_OLD_END) + len(HEAD_OLD_END):]

header = '''/-
D63 lane L48 (2026-11-10), part 6: **the app's top theorem with the stages' openings at their REAL width** (finding
L45-2, decision D77a). GENERATED by `results/zk60_lean_l48_20261110/l48_mk_top.py` from lane L45's generated
`RunExtractTop.lean`.

L45's `rx_productionReadyL_r13P_exec_own` asked `RkPcsR13` (`log_cols 14`, `N = 2^16`) of the two stages' `A` and `H`
verifiers (`hIA`, `hIH`, `hOA`, `hOH`), which the real stages (`2^12`, rate `1/4`) cannot meet. Here they are asked at
the tier's stage geometry `ogStage` (`RkPcsAt U tag ogStage`), which the real stage verifiers MEET
(`RunOpenGeoStage.lean`: `rcIncAt_pA_stage`, `rcIncAt_pH_stage`, `rcOutcAt_pA_stage`, `rcOutcAt_pH_stage`, at the tier
numbers `RunOpenGeoCheck.lean` checks against the code), and the kinds data's stage parts are at that geometry
(`rxDinG ogStage`, `rxDoutG ogStage`). Everything else is L45's statement, unchanged.

* **`og_productionReadyL_r13P_exec_stage`**.

Only `propext`, `Classical.choice`, `Quot.sound`.
-/
import ZK60Formal.RunCoverPRk
import ZK60Formal.RunExtractParts
import ZK60Formal.RunOpenGeoTier
'''


def sub(text, old, new, count):
    n = text.count(old)
    assert n == count, (old, n, count)
    return text.replace(old, new)


b = body
b = sub(b, "section OwnTop", "section OgTop", 1)
b = sub(b, "end OwnTop", "end OgTop", 1)
b = sub(b, "theorem rx_productionReadyL_r13P_exec_own", "theorem og_productionReadyL_r13P_exec_stage", 1)
b = sub(b, "/-- **THE APP'S TOP THEOREM WITH THE RUN'S OWN MERKLE WORK AND THE KINDS DATA'S READERS BUILT** (D63 lane L45).",
        "/-- **THE APP'S TOP THEOREM WITH THE STAGES' OPENINGS AT THEIR REAL WIDTH** (D63 lane L48; L45's\n"
        "`rx_productionReadyL_r13P_exec_own` with `hIA`, `hIH`, `hOA`, `hOH` at the tier's stage geometry `ogStage`, met by\n"
        "the real stage verifiers). As L45's:", 1)
b = sub(b, "(hIA : RkPcsR13 U tag Iin.pA) (hIH : RkPcsR13 U tag Iin.pH) (hOA : RkPcsR13 U tag Oout.pA)\n"
           "    (hOH : RkPcsR13 U tag Oout.pH)",
        "(hIA : RkPcsAt U tag ogStage Iin.pA) (hIH : RkPcsAt U tag ogStage Iin.pH)\n"
        "    (hOA : RkPcsAt U tag ogStage Oout.pA) (hOH : RkPcsAt U tag ogStage Oout.pH)", 1)
n_din = b.count("rxDin (RtRun.pf Rn)")
n_dout = b.count("rxDout (RtRun.pf Rn)")
assert n_din == n_dout and n_din >= 3, (n_din, n_dout)
b = b.replace("rxDin (RtRun.pf Rn)", "rxDinG ogStage (RtRun.pf Rn)")
b = b.replace("rxDout (RtRun.pf Rn)", "rxDoutG ogStage (RtRun.pf Rn)")
b = sub(b, "rx_parts_AH (U := U)", "rx_parts_AHG (U := U) (gS := ogStage) (hgS := ogStage_ok) (hgSQ := le_rfl)", 2)
b = sub(b, "rx_parts_M (tag := tag)", "rx_parts_MG (tag := tag) (gS := ogStage)", 1)
assert "rkR13" not in b
open(WT + "/formal/ZK60Formal/RunOpenGeoTop.lean", "w").write(header + b)
print("RunOpenGeoTop.lean written: rxDin/rxDout replaced %d times each" % n_din)
