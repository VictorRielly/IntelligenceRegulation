#!/usr/bin/env python3
"""D63 lane L46 (2026-11-10; a copy of L44's): write the axiom audit file, a `#print axioms` line for EVERY theorem, definition, abbreviation
and structure of the L31 library files, qualified by the namespaces each file opens. From
results/zk60_lean_l26_20261107/gen_axioms.py, with the modules given on the command line.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean> <Module> [<Module> ...]
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
mods = sys.argv[3:]
lines = [f"import ZK60Formal.{m}" for m in mods] + [
    "",
    "-- D63 lane L46 (2026-11-10): the audit of the doom covers (generated by gen_axioms.py: every `theorem`,",
    "-- `def`, `abbrev` and `structure` of the lane's library files).",
    "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
    ""]
counts = {}
for m in mods:
    stack = []
    lines.append(f"-- {m}.lean")
    for raw in open(f"{src}/{m}.lean"):
        mm = re.match(r"^namespace (\S+)", raw)
        if mm:
            stack.append(mm.group(1))
            continue
        mm = re.match(r"^end (\S+)", raw)
        if mm and stack and stack[-1] == mm.group(1):
            stack.pop()
            continue
        mm = re.match(r"^(?:noncomputable )?(theorem|def|abbrev|structure) (\S+)", raw)
        if mm:
            kind, name = mm.group(1), mm.group(2)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            counts[kind] = counts.get(kind, 0) + 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{sum(counts.values())} declarations: " + ", ".join(f"{counts[k]} {k}" for k in sorted(counts)))
