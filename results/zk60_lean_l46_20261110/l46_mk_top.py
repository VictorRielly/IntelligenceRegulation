#!/usr/bin/env python3
"""D63 lane L46 (2026-11-10): generate formal/ZK60Formal/RunDoomTop.lean from L43's RunCoverPRk.lean.

The app's top theorem `rc_productionReadyL_r13P_exec_rk` is copied with exactly these changes:
  * its name becomes `rd_productionReadyL_r13P_exec_blk`, its docstring is replaced;
  * its premise `hdblk` (the block cover) is replaced by `hblk` (every block's bundle
    `RdBlkR13` at its own shape on every accepted outcome outside the extraction failure);
  * its proof applies `rc_productionReadyL_r13P_exec_rk` with every argument by name and
    `hdblk := rd_hdblk ...` (RunDoomBlk.lean).
Each replacement asserts its count of matches.

usage: python3 -I l46_mk_top.py <formal/ZK60Formal dir> [<output file; default the dir's RunDoomTop.lean>]
"""
import sys
import os

src_dir = sys.argv[1]
src = open(os.path.join(src_dir, "RunCoverPRk.lean"), encoding="utf-8").read()

# 1. the theorem's statement, from its docstring to `:=`
start = src.index("/-- **THE APP'S TOP THEOREM IN D76'S APPROVED FORM")
thm = src.index("theorem rc_productionReadyL_r13P_exec_rk", start)
end = src.index("  by\n  subst hDe", thm)
stmt = src[thm:end]
assert stmt.count("theorem rc_productionReadyL_r13P_exec_rk") == 1

# 2. the hdblk premise, replaced
h0 = stmt.index("    (hdblk : ")
h1 = stmt.index("    (hdout : ")
old_hdblk = stmt[h0:h1]
assert old_hdblk.count("(hdblk :") == 1
VERIFY = ("(classifyProtocolUExecP Rp Lq Lb preA preB start inc incG blk outc outcG P (CinR) h64 hr hon.base 24448)"
          ".verify G () (A.runLog G).1.1 (A.runLog G).1.2 = true")
EVX = "¬ EvXR tag Lq h64 C 256 256 256 16 16 12 26 coreOf Vx rx A G"
assert old_hdblk.count(VERIFY) == 1 and old_hdblk.count(EVX) == 1
new_hblk = (
    "    (hblk : ∀ (A : OC (QB Lq) Dig (ClsStmt Hdr × ClsReceipt)) (G : QB Lq → Dig) (k : ℕ) (hk : k < Rp.blks.length),\n"
    "      " + VERIFY + " →\n"
    "      " + EVX + " →\n"
    "      Nonempty (ZK60.ProtocolClassify.RdBlkR13 U D k (A.runLog G).2\n"
    "        (rtTr key domain Lq (RtRun.pf Rn) (RtRun.rd Rn) G (A.run G))\n"
    "        (Exec.Block.absOfC (chainEncB key domain hs Lq hL)) (ZK60.Exec.Block.card_K_gt K) Rp.blks[k].pub\n"
    "        ((E (A.runLog G).2 (A.runLog G).1.1 (A.runLog G).1.2).planes k)\n"
    "        ((E (A.runLog G).2 (A.runLog G).1.1 (A.runLog G).1.2).planes (k + 1))))\n")
stmt = stmt[:h0] + new_hblk + stmt[h1:]
stmt = stmt.replace("theorem rc_productionReadyL_r13P_exec_rk", "theorem rd_productionReadyL_r13P_exec_blk", 1)

# 3. the proof
names = ["Rr", "dR", "hpos", "place", "msg", "msg_place", "pad", "salt", "path", "tagc", "Rp", "Lq", "Lb", "preA",
         "preB", "start", "inc", "incG", "blk", "outc", "outcG", "P", "h64", "hr", "hon", "U", "hbij", "key", "domain",
         "hs", "hL", "hL64", "Rn", "hv", "D", "hD", "site", "kOf", "δOf", "E", "O", "T", "hTenc", "hTaA", "hTaB", "Ux",
         "Xx", "hUc", "hXc", "pr", "hp1", "hp2", "hF", "hw0", "hβLR", "hTe", "hTQ", "hβJ", "tag", "C", "coreOf", "Vx",
         "nx", "hVx", "hnx", "rx", "nrx", "hrx", "hnrx", "hU", "ps", "acc", "lsc", "eL", "hDe", "hopW", "hMW",
         "hal_slots", "hal_R0", "hal_R1", "hal_H0", "hal_H1", "hal_LU", "hdin", "hdout", "mk", "ops", "hE", "hops",
         "hcan", "hwin", "hread", "hBal", "hdzero", "hzk"]
for n in names:
    assert ("(" + n + " ") in stmt or (" " + n + " :") in stmt or n in ("Rr", "dR", "hpos", "place", "msg",
        "msg_place", "pad", "salt", "path", "tagc"), n
# wrap the argument list at 116 columns
lines, cur = [], "    "
for piece in ("(%s := %s)" % (n, n) for n in names):
    if len(cur) + len(piece) + 1 > 116:
        lines.append(cur.rstrip())
        cur = "    "
    cur += piece + " "
lines.append(cur.rstrip())
proof = (
    "  by\n"
    "  exact rc_productionReadyL_r13P_exec_rk\n"
    + "\n".join(lines) + "\n"
    "    (hdblk := fun A G k hk hv' hx' => ZK60.ProtocolClassify.rd_hdblk key domain hs Lq hL (RtRun.pf Rn) (RtRun.rd Rn)\n"
    "      hL64 hv U hbij D hD Rp ((RtRun.parts_length Rn).trans (congrArg (fun n => n + 2) O.blocks.2))\n"
    "      (Exec.Block.absOfC (chainEncB key domain hs Lq hL))\n"
    "      (ZK60.Exec.Block.card_K_gt K)\n"
    "      (fun A G => " + VERIFY + "\n"
    "        ∧ " + EVX + ")\n"
    "      (fun A G => (E (A.runLog G).2 (A.runLog G).1.1 (A.runLog G).1.2).planes)\n"
    "      (fun A G k hk hacc => hblk A G k hk hacc.1 hacc.2) A G k hk ⟨hv', hx'⟩)\n")

# 4. the file: L43's header and section, the new docstring
hdr_end = src.index("/-- **THE APP'S TOP THEOREM IN D76'S APPROVED FORM")
sec_start = src.index("section RkTop")
section_head = src[sec_start:hdr_end].replace("section RkTop", "section RdTop", 1)
doc = '''/-
D63 lane L46 (2026-11-10), part 2: **the app's top theorem with the block cover `hdblk` discharged to the blocks'
bundles** (`RdBlkR13`, RunDoomBlk.lean). GENERATED by `results/zk60_lean_l46_20261110/l46_mk_top.py` from L43's
RunCoverPRk.lean: L43's `rc_productionReadyL_r13P_exec_rk` with its premise `hdblk` replaced by `hblk` and applied with
`hdblk := rd_hdblk …`.

* **`rd_productionReadyL_r13P_exec_blk`**.

Only `propext`, `Classical.choice`, `Quot.sound`.
-/
import ZK60Formal.RunDoomBlk

set_option autoImplicit false
set_option linter.constructorNameAsVariable false

namespace ZK60.ProtocolClassify.RunShapeP

open scoped ENNReal
open ZK60 ZK60.Exec ZK60.TokenRun ZK60.Sound ZK60.Assembly ZK60.StageX ZK60.Exec.Link Code ZK60.RunShape
open ZK60.Exec.StageV (IncV OutcV StageGeom classifyRunV classifyProtocolExec)
open ZK60.Circuit (gP GF)
open ZK60.Block (BlockShape BlockPublic BlockSat)
open ZK60.D76 (LeaksAtMost productionReadyL_of_productionReady productionReadyL_of_productionReady_range)

'''
thm_doc = '''/-- **THE APP'S TOP THEOREM WITH THE BLOCK COVER DISCHARGED TO THE BLOCKS' BUNDLES** (D63 lane L46).
`rc_productionReadyL_r13P_exec_rk` (D76's approved form, one shape per block, `D := rkData …`) with its premise
`hdblk` replaced by `hblk`: on every accepted outcome outside the run's extraction failure, every block `k` has its
R13 bundle `RdBlkR13` at its own shape `Rp.blks[k]`, on the run's planes `k`, `k + 1` (the block's R13 objects with
L36's `R13Spec`, the run's define and LogUp lists in part `k + 1`, the boundary slots' link, L36's lookup side
`hTtab`, `hcov`). `hdblk` is then `rd_hdblk` (L27's `block_doom_r13` with its links). Generated. -/
'''
out = doc + section_head + thm_doc + stmt + proof + "\nend RdTop\n\nend ZK60.ProtocolClassify.RunShapeP\n"
assert out.count("(hdblk : ∀") == 0 and out.count("(hblk :") == 1 and out.count("(hdblk := ") == 1
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(src_dir, "RunDoomTop.lean")
open(dst, "w", encoding="utf-8").write(out)
print("wrote", dst + ",", len(out.splitlines()), "lines")
