    print("Exact-arithmetic re-check of the masked-sumcheck DOF count")
    print("prime field P = 2^31 - 1 (an ILLUSTRATION; the real field is Fp2, |Fp2| = 2^128)")
    print()

    # --- layout arithmetic, independent of any rank
    L_total = sum(mask_len(n, d) for n, d in SLOTS)
    rounds_total = sum(n for n, _ in SLOTS)
    values_total = sum(n * (d + 1) for n, d in SLOTS)
    dimC_total = sum(n * d + 1 for n, d in SLOTS)
    print(f"23 slots: sum L_s            = {L_total}   (memo: 583)")
    print(f"          sum (n+ext)        = {rounds_total}   (memo: 184 = 159 main + 25 extension)")
    print(f"          sum (n+ext)(d+1)   = {values_total}   (memo: 721 published round values)")
    print(f"          sum dim C_s        = {dimC_total}   (memo: 560 = dim C)")
    print(f"          largest L_s        = {max(mask_len(n, d) for n, d in SLOTS)}   (memo: 50 <= 256)")
    print()

    regimes = {
        "random": lambda n: [rnd.randrange(1, P) for _ in range(n)],
        "all-zero": lambda n: [0] * n,
        "all-one": lambda n: [1] * n,
        "all-equal": lambda n: [7] * n,
        "small": lambda n: [i + 2 for i in range(n)],
    }

    bad = 0
    checked = 0
    aprime_still_covers = 0
    drop_last_point_rank = []

    print("per slot, per rho regime: rank(R) / dim C / dim ker R / weights in rowspace")
    for si, (n, d) in enumerate(SLOTS):
        L = mask_len(n, d)
        for rname, rgen in regimes.items():
            rho = rgen(n)
            M, ncols = round_matrix(n, d, rho)
            rk = rank(M, ncols)
            dimC, nconstraints = consistency_dim(n, d, rho)
            ker = L - rk
            ok_rank = (rk == n * d + 1) and (dimC == n * d + 1) and (ker == 1)

            # the two published weight families must lie in the row span of R
            sw = sum_weights(n, d)
            ew = eval_weights(rho, d)
            in_span_sum = rank(M + [sw], ncols) == rk
            in_span_eval = rank(M + [ew], ncols) == rk

            # control: drop a' from the coefficient vector
