    print("         i.e. the mask STILL covers C_s exactly without a'.  So a' is a")
    print("         redundancy of the parametrisation, not the freedom that makes the")
    print("         total and the terminal uniform given the (unmasked) round messages.")
    print("         The code comment at zkp-core/src/sumcheck.rs:163-183 says otherwise")
    print("         and should be reconciled.  Nothing in the memo depends on this.")
    print()
    drops = sorted(set(r[3] - r[2] for r in drop_last_point_rank))
    kers = sorted(set(r[4] for r in drop_last_point_rank))
    print("RESULT 4 (the d+1-values invariant, ruling G-3):")
    print(f"         publishing only d values per round (dropping X = d) drops the rank")
    print(f"         by {drops} and raises dim ker R to {kers}, shape by shape.")
    print("         So the invariant IS load-bearing: with d values the mask no longer")
    print("         covers C_s.  The lemma's own control reports kernel dimension 2 at")
    print("         slots 8 and 17; the exact figure depends on which evaluation point is")
