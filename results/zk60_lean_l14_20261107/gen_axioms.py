#!/usr/bin/env python3
"""D63 step L14 (2026-11-07): write axioms_l14.lean, a `#print axioms` line for EVERY theorem of the L14 library files
(ZKW16Prog.lean, ZKW16Step.lean, ZKW16View.lean, ZKW16Block.lean, ZKW16Hyb.lean, ZKW16Shape.lean), qualified by the namespaces each
file opens. A copy of results/zk60_lean_l11_20261107/gen_axioms.py with the L14 files.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["ZKW16Prog.lean", "ZKW16Step.lean", "ZKW16View.lean", "ZKW16Block.lean", "ZKW16Hyb.lean", "ZKW16Shape.lean"]
lines = ["import ZK60Formal.ZKW16Shape", "",
         "-- D63 step L14 (2026-11-07): the axiom audit of the zero-knowledge lane's files",
         "-- (generated by gen_axioms.py: every `theorem` of the six L14 files). Each must show at most `propext`,",
         "-- `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).", ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = ".".join(stack + [m.group(1)])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
