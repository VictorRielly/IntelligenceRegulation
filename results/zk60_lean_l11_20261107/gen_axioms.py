#!/usr/bin/env python3
"""D63 step L11 (2026-11-07): write axioms_l11.lean, a `#print axioms` line for EVERY theorem of the five L11 library
files (SlotW16Ir.lean, SlotW16R2.lean, SlotW16Sound.lean, LayoutW16.lean, LayoutW16Handoff.lean), qualified by the namespaces each file opens.
A copy of results/zk60_lean_l8_20261106/gen_axioms.py with the L11 files.

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["SlotW16Ir.lean", "SlotW16R2.lean", "SlotW16Sound.lean", "LayoutW16.lean", "LayoutW16Handoff.lean"]
lines = ["import ZK60Formal.SlotW16R2", "import ZK60Formal.LayoutW16Handoff", "",
         "-- D63 step L11 (2026-11-07): the axiom audit of the W16R2 slot arithmetization and layout map",
         "-- (generated by gen_axioms.py: every `theorem` of the five L11 files). Each must show at most `propext`,",
         "-- `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).", ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = ".".join(stack + [m.group(1)])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
