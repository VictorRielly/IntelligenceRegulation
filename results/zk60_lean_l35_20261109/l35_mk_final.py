def binder_names(sig):
    """The explicit binders' names of a theorem's signature, in order (comments removed; stops at the depth-0 ':')."""
    text = "\n".join(l.split("--")[0] for l in sig.split("\n"))
    text = text[text.index(" ", len("theorem ")):]  # after the name
    names, depth, i, start = [], 0, 0, None
    opener = None
    while i < len(text):
        ch = text[i]
        if ch in "([{":
            if depth == 0:
                start, opener = i, ch
            depth += 1
        elif ch in ")]}":
            depth -= 1
            if depth == 0 and opener == "(":
                grp = text[start + 1:i]
                names += grp.split(" : ", 1)[0].split()
        elif ch == ":" and depth == 0:
            break
        i += 1
    return names


