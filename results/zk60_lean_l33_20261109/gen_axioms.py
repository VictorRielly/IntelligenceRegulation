#!/usr/bin/env python3
"""D63 lane L33 (2026-11-09): write axioms_l33.lean, a `#print axioms` line for EVERY theorem, definition, abbreviation,
structure, inductive and instance of the L33 library files, qualified by the namespaces each file opens. From
results/zk60_lean_l26_20261107/gen_axioms.py, with this lane's files (nested namespaces are a stack; an `inductive` and
a named `instance` are audited too).

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = ["ZKHonestProg.lean", "ZKHonestStep.lean", "ZKHonestView.lean", "ZKHonestCount.lean", "ZKHonestRun.lean"]
lines = ["import ZK60Formal.ZKHonestRun", "",
         "-- D63 lane L33 (2026-11-09): the audit of the honest prover as a receipt model, the refusal-aware step, the",
         "-- view links, the counts and the classify run's zero knowledge (generated by gen_axioms.py: every `theorem`,",
         "-- `def`, `abbrev`, `structure`, `inductive` and `instance` of the five library files).",
         "-- Each must show at most `propext`, `Classical.choice`, `Quot.sound` (no `sorryAx`, no `Lean.ofReduceBool`).",
         ""]
counts = {}
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^(?:noncomputable )?(theorem|def|abbrev|structure|inductive|instance) (\S+)", raw)
        if m:
            kind, name = m.group(1), m.group(2)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            counts[kind] = counts.get(kind, 0) + 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{sum(counts.values())} declarations: " + ", ".join(f"{counts[k]} {k}" for k in sorted(counts)))
