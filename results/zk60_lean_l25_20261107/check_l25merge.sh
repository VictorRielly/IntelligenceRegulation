#!/bin/bash
# D63 step L25 (the honest provers and completeness), merged into perf after L9-L17 and
# A24: the check on the MERGED tree in the main checkout. L25 adds no Rust. The full Lean build; the L25, L22, L24, L23, L21, L19, L20, L16, L14, L13, L15,
# L10, L12, L9 and L11 axiom audits; the source scan of the five L25 files (L14's header sentence filter is kept,
# harmless here); and as regressions ExecBlockCheck,
# L11Check, L6Check, L5Check and the fixture L1 check. One guarded job, class cpu.
set -u
R=/Users/victorrielly/IntelligenceRegulation
O=$R/results/zk60_lean_l25_20261107
O22=$R/results/zk60_lean_l22_20261107
O24=$R/results/zk60_lean_l24_20261107
O21=$R/results/zk60_lean_l21_20261107
O23=$R/results/zk60_lean_l23_20261107
O19=$R/results/zk60_lean_l19_20261107
O20=$R/results/zk60_lean_l20_20261107
O16=$R/results/zk60_lean_l16_20261107
O14=$R/results/zk60_lean_l14_20261107
O13=$R/results/zk60_lean_l13_20261107
O15=$R/results/zk60_lean_l15_20261107
O10=$R/results/zk60_lean_l10_20261107
O12=$R/results/zk60_lean_l12_20261107
O9=$R/results/zk60_lean_l9_20261107
O11=$R/results/zk60_lean_l11_20261107
O6=$R/results/zk60_lean_l6_20261106
O5=$R/results/zk60_lean_l5_20261106
R1=$R/results/zk60_lean_l1l2_20261106
V=$R/ops/zkp-mvp/gpu-metal/hashline/src/private_block/r13_vectors
L=$R/formal/ZK60Formal
F=/private/tmp/claude-501/-Users-victorrielly-IntelligenceRegulation/01ce547c-a1e2-4e9f-8e3d-f16c477ac05b/scratchpad/l9merge/fork_frame.bin
LAKE=/Users/victorrielly/.elan/toolchains/leanprover--lean4---v4.34.1/bin/lake
P=$O/l25merge.progress
say() { echo "$(date -u +%FT%TZ) $*" >> $P; }
say start
$LAKE -d $R/formal build > $O/l25merge_lake.log 2>&1; say "lake build rc=$?"
tail -2 $O/l25merge_lake.log >> $P
grep -ciE "warning|sorry" $O/l25merge_lake.log | sed 's/^/lines naming a warning or sorry in the build log: /' >> $P
for A in $O/axioms_l25.lean $O22/axioms_l22.lean $O24/axioms_l24.lean $O23/axioms_l23.lean $O21/axioms_l21.lean $O19/axioms_l19.lean $O20/axioms_l20.lean $O16/axioms_l16.lean $O14/axioms_l14.lean $O13/axioms_l13.lean $O15/axioms_l15.lean $O10/axioms_l10.lean $O12/axioms_l12.lean \
         $O9/axioms_l9.lean $O11/axioms_l11.lean; do
  b=$(basename $A .lean)
  $LAKE -d $R/formal env lean $A > $O/l25merge_$b.log 2>&1; say "axiom audit $b rc=$?"
  grep -cE "sorryAx|ofReduceBool" $O/l25merge_$b.log | sed 's/^/sorryAx or ofReduceBool mentions: /' >> $P
  grep -oE "axioms: \[[^]]*\]" $O/l25merge_$b.log | sort | uniq -c >> $P
done
grep -n -E '\bsorry\b|\baxiom\b|native_decide|admit|maxRecDepth|maxHeartbeats|implemented_by|@\[extern|bv_decide|ofReduceBool' \
  $L/HonestClassifySum.lean $L/HonestClassifyBlock.lean $L/HonestClassifyRun.lean $L/HonestClassifyCount.lean $L/HonestClassifyLinks.lean \
  | grep -v 'Every premise is an explicit hypothesis; no `sorry`, axiom or `native_decide`.' > $O/l25merge_scan.log
say "source scan hits other than the header sentence (grep rc 1 = none): rc=$?"
ulimit -s 65520
$LAKE -d $R/formal env lean --run $L/ExecBlockCheck.lean $O9/corpus.txt $F > $O/l25merge_l9check.log 2>&1
say "ExecBlockCheck regression rc=$?"
tail -1 $O/l25merge_l9check.log >> $P
$LAKE -d $R/formal env lean --run $L/L11Check.lean $O11/corpus.txt > $O/l25merge_l11check.log 2>&1; say "L11Check rc=$?"
tail -1 $O/l25merge_l11check.log >> $P
$LAKE -d $R/formal env lean --run $L/L6Check.lean $O6/corpus.txt > $O/l25merge_l6check.log 2>&1; say "L6Check rc=$?"
tail -1 $O/l25merge_l6check.log >> $P
$LAKE -d $R/formal env lean --run $L/L5Check.lean $O5/corpus.txt > $O/l25merge_l5check.log 2>&1; say "L5Check rc=$?"
tail -1 $O/l25merge_l5check.log >> $P
$LAKE -d $R/formal env lean --run $L/L1Check.lean $V/block_fixture_t32.tsv \
  $V/block_trace_low_h24_t32.tsv $V/block_trace_low_t32.tsv $R1/rust_fixture_trace.tsv $V/r13_requant_vectors.tsv \
  > $O/l25merge_l1check.log 2>&1; say "fixture L1 check rc=$?"
tail -1 $O/l25merge_l1check.log >> $P
say "all done"
# R13 regression (L25's block prover is generic over BlockParams; L23-1's line is in ExecBlockVerify): CheckR13Block on
# the consistent segment pair regenerated by check_l17merge.sh into scratch.
S17=/private/tmp/claude-501/-Users-victorrielly-IntelligenceRegulation/01ce547c-a1e2-4e9f-8e3d-f16c477ac05b/scratchpad/l17merge/out
O17=$R/results/zk60_lean_l17_20261107
$LAKE -d $R/formal env lean --run $L/CheckR13Block.lean $O17/block_corpus.txt $S17/fork_frame.bin $S17/segment_corpus.txt \
  $S17/segment.bin > $O/l25merge_r13block.log 2>&1; say "CheckR13Block regression rc=$?"
tail -1 $O/l25merge_r13block.log >> $P
say "all done (R13)"
