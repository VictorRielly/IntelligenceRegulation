#!/usr/bin/env python3
"""D63 lane L28 (2026-11-07): write axioms_l28.lean, a `#print axioms` line for EVERY theorem of the L28 library files,
qualified by the namespaces each file opens. A copy of results/zk60_lean_l22_20261107/gen_axioms.py with this lane's
files (and `OProf.` namespaces inside the files).

usage: python3 -I gen_axioms.py <formal/ZK60Formal dir> <out.lean>
"""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
files = [f for f in ["LinkW16Pcs.lean", "LinkW16Head.lean", "LinkW16Glue.lean", "LinkW16GlueW16.lean", "LinkW16GlueW16T.lean",
                     "LinkW16GlueR13.lean"] if os.path.exists(f"{src}/{f}")]
lines = [f"import ZK60Formal.{f[:-5]}" for f in files] + ["",
         "-- D63 lane L28 (2026-11-07): the audit of the openings' glue (generated by gen_axioms.py: every",
         "-- `theorem` of the L28 library files). Each must show at most `propext`, `Classical.choice`, `Quot.sound`.",
         ""]
count = 0
for f in files:
    stack = []
    lines.append(f"-- {f}")
    for raw in open(f"{src}/{f}"):
        m = re.match(r"^namespace (\S+)", raw)
        if m:
            stack.append(m.group(1))
            continue
        m = re.match(r"^end (\S+)", raw)
        if m and stack and stack[-1] == m.group(1):
            stack.pop()
            continue
        m = re.match(r"^theorem (\S+)", raw)
        if m:
            name = m.group(1)
            if name.startswith("_root_."):
                name = name[len("_root_."):]
            else:
                name = ".".join(stack + [name])
            lines.append(f"#print axioms {name}")
            count += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"{count} theorems")
