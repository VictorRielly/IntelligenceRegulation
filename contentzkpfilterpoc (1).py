# --- THE ZK-FRIENDLY MODEL ---
class ZKNativeFilter(nn.Module):
    def __init__(self, vocab_size=VOCAB_SIZE, embed_dim=8, num_filters=4):
        super().__init__()
        self.embedding = nn.Embedding(vocab_size, embed_dim)
        self.conv1 = nn.Conv1d(in_channels=embed_dim, out_channels=num_filters, kernel_size=3, padding=1)
        self.relu = nn.ReLU()
        self.pool = nn.AdaptiveAvgPool1d(1)
        self.fc = nn.Linear(num_filters, 2)

    def forward(self, x):
        emb = self.embedding(x)
        emb = emb.transpose(1, 2)
        features = self.conv1(emb)
        features = self.relu(features)
        pooled = self.pool(features).squeeze(-1)
        return self.fc(pooled)

# --- PART 1: Crypto Vector Generation ---
def generate_crypto_vectors():
    print("\n[Step 1] Generating Crypto Test Vectors...")
    key = os.urandom(16)
    iv = os.urandom(16)
    plaintext_msg = "I will hurt you."

    block_size = 16
    data_bytes = plaintext_msg.encode('utf-8')
    padding_len = block_size - (len(data_bytes) % block_size)
    padded_data = data_bytes + bytes([padding_len] * padding_len)

    cipher = Cipher(algorithms.AES(key), modes.CBC(iv), backend=default_backend())
    encryptor = cipher.encryptor()
    ciphertext = encryptor.update(padded_data) + encryptor.finalize()

    witness_data = {
        "key_hex": key.hex(),
        "iv_hex": iv.hex(),
        "plaintext_utf8": plaintext_msg,
        "ciphertext_hex": ciphertext.hex()
    }
    with open(CRYPTO_WITNESS_PATH, "w") as f:
        json.dump(witness_data, f, indent=4)
    print(f"[+] Crypto vectors generated.")

