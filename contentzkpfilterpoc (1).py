# --- THE ZK-FRIENDLY BERT WRAPPER ---
# Since ezkl works best with single-input tensors, we wrap the BERT model
# to handle the attention mask generation internally.
class ZKBERTWrapper(nn.Module):
    def __init__(self, model):
        super().__init__()
        self.model = model

    def forward(self, input_ids):
        # Generate an attention mask of ones for the sequence length
        # This is valid for fixed-length ZK circuits.
        attention_mask = torch.ones_like(input_ids)
        outputs = self.model(input_ids=input_ids, attention_mask=attention_mask)
        return outputs.logits

