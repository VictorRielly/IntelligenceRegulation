"""Ownership-transfer + factorized equality arithmetic, NOT a private protocol.

The original ordered leaf source and retained checkpoints remain immutable.
Only the reduce/equality helpers are retained here. The imported prior source
used F65537; this port is exercised over native Goldilocks Fp2.
"""
def mix(a,b,p):
    return ((a[0]*b[1]+a[1]*b[0])%p,a[1]*b[1]%p)

def reduce_at(read,start,n,p,count):
    if n==1:
        count['leaves']+=1
        a,b=read(start)
        if b%p==0: raise ValueError('zero denominator even at zero multiplicity')
        return a,b
    l=reduce_at(read,start,n//2,p,count)
    r=reduce_at(read,start+n//2,n//2,p,count)
    count['internal']+=1
    return mix(l,r,p)

def weights(point,p):
    # Low-bit-first, generated by expansion; no inverses, including at 0/1.
    # Fixed final capacity avoids holding old+new expansion arrays at once.
    a=[0]*(1<<len(point));a[0]=1;active=1
    for z in reversed(point):
        for j in range(active-1,-1,-1):
            v=a[j];a[2*j]=v*(1-z)%p;a[2*j+1]=v*z%p
        active*=2
    return a

def tensor(point,p):
    cut=len(point)//2
    return weights(point[:cut],p),weights(point[cut:],p),cut

def eq_at(a,b,cut,j,p): return a[j&((1<<cut)-1)]*b[j>>cut]%p

