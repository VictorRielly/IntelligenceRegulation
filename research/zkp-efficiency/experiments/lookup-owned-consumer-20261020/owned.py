"""Ownership-transfer + factorized equality arithmetic, NOT a private protocol.

The original ordered leaf source and retained checkpoints remain immutable.
Only freshly allocated four-plane buffers are consumed. All capacities persist
until the layer ends. Fp2 sizes are symbolic; arithmetic tests use F65537.
"""
def mix(a,b,p):
    return ((a[0]*b[1]+a[1]*b[0])%p,a[1]*b[1]%p)

def reduce_at(read,start,n,p,count):
    if n==1:
        count['leaves']+=1
        a,b=read(start)
        if b%p==0: raise ValueError('zero denominator even at zero multiplicity')
        return a,b
    l=reduce_at(read,start,n//2,p,count)
    r=reduce_at(read,start+n//2,n//2,p,count)
    count['internal']+=1
    return mix(l,r,p)

def weights(point,p):
    # Low-bit-first, generated by expansion; no inverses, including at 0/1.
    # Fixed final capacity avoids holding old+new expansion arrays at once.
    a=[0]*(1<<len(point));a[0]=1;active=1
    for z in reversed(point):
        for j in range(active-1,-1,-1):
            v=a[j];a[2*j]=v*(1-z)%p;a[2*j+1]=v*z%p
        active*=2
    return a

def tensor(point,p):
    cut=len(point)//2
    return weights(point[:cut],p),weights(point[cut:],p),cut

def eq_at(a,b,cut,j,p): return a[j&((1<<cut)-1)]*b[j>>cut]%p

class OwnedPlanes:
    def __init__(self,planes,origin):
        if origin not in ('regenerated','checkpoint_copy'): raise ValueError('borrowed child')
        if len(planes)!=4 or len({id(v) for v in planes})!=4: raise ValueError('aliased planes')
        if not planes[0] or any(len(v)!=len(planes[0]) for v in planes): raise ValueError('shape')
        self.planes=planes;self.origin=origin;self.used=False

def serve(read,n,b,p):
    """A sequential ordered source is revisited on reconstruction; it is not free.
    Tiny cache is tuples; regen writes directly into final four mutable planes.
    """
    h=n.bit_length()-1;b=min(b,h);count={'leaves':0,'internal':0,'checkpoint_scalar_copies':0}
    cache={b:tuple(reduce_at(read,j*n//(1<<b),n//(1<<b),p,count) for j in range(1<<b))}
    for d in range(b-1,-1,-1):
        c=cache[d+1];cache[d]=tuple(mix(c[j],c[j+1],p) for j in range(0,len(c),2))
        count['internal']+=len(cache[d])
    for d in range(1,h+1):
        w=1<<d;planes=[[0]*(w//2) for _ in range(4)]
        for j in range(w):
            if d<=b:
                value=cache[d][j];count['checkpoint_scalar_copies']+=2
            else: value=reduce_at(read,j*n//w,n//w,p,count)
            side=j%2;idx=j//2
            planes[2*side][idx],planes[2*side+1][idx]=value
        yield d,OwnedPlanes(planes,'checkpoint_copy' if d<=b else 'regenerated'),cache,count
        # Consumer must finish/drop its owner before requesting the next layer.
        # The tiny differential harness retains extra oracle objects; its RSS is
        # not this symbolic phase model's measured allocation high-water mark.
        del planes

def consume(owner,point,challenges,lam,p):
    if owner.used: raise ValueError('owner already consumed')
    v=owner.planes;n=len(v[0]);k=n.bit_length()-1
    if n!=1<<k or len(point)!=k or len(challenges)!=k: raise ValueError('shape')
    owner.used=True;prefix=1;active=n;samples=[];eq_entries=0;eq_table_muls=0
    def term(a,b,c,d): return (a*d+c*b+lam*b*d)%p
    if not k: return term(*(a[0] for a in v)),[],term(*(a[0] for a in v)),v,dict(eq_entries=0,eq_table_muls=0)
    for t,r in enumerate(challenges):
        lo,hi,cut=tensor(point[t+1:],p)
        eq_entries+=len(lo)+len(hi)
        eq_table_muls+=2*((len(lo)-1)+(len(hi)-1))
        row=[0]*4
        currents=[((1-point[t])*(1-x)+point[t]*x)%p for x in range(4)]
        for j in range(active//2):
            e=prefix*eq_at(lo,hi,cut,j,p)%p
            for x in range(4):
                folded=[(a[2*j]+x*(a[2*j+1]-a[2*j]))%p for a in v]
                row[x]=(row[x]+e*currents[x]*term(*folded))%p
        samples.append(row)
        for a in v:
            for j in range(active//2): a[j]=(a[2*j]+r*(a[2*j+1]-a[2*j]))%p
        prefix=prefix*((1-point[t])*(1-r)+point[t]*r)%p
        active//=2
        # The two factor tables die before the next round constructs its tables.
        del lo,hi
    terminal=prefix*term(*(a[0] for a in v))%p
    return (samples[0][0]+samples[0][1])%p,samples,terminal,v,dict(eq_entries=eq_entries,eq_table_muls=eq_table_muls)

class Arena:
    def __init__(self):self.live={};self.peak=0;self.events=[]
    def add(self,key,size):
        assert key not in self.live
        self.live[key]=size;self.peak=max(self.peak,sum(self.live.values()))
        self.events.append(('alloc',key,size,sum(self.live.values())))
    def drop(self,key):
        z=self.live.pop(key);self.events.append(('drop',key,z,sum(self.live.values())))

def eq_slots(k):
    if k==0:return 0
    tail=k-1
    return (1<<(tail//2))+(1<<(tail-tail//2))

def allocation_trace(sizes,b,mode):
    assert sizes and mode in ('forest','column') and b>=0
    assert all(n>=2 and n&(n-1)==0 for n in sizes)
    hs=[n.bit_length()-1 for n in sizes];a=Arena();k=len(sizes)
    a.add('roots',32*(2*k-1))
    if mode=='forest':
        for i,h in enumerate(hs):a.add('cache'+str(i),32*((1<<(min(b,h)+1))-1))
    a.add('root_dfs',32*(max(hs)+1));a.drop('root_dfs')
    work=sum(n-1 for n in sizes)+k-1;leaves=sum(sizes);copies=0;entries=0
    for i,(n,h) in enumerate(zip(sizes,hs)):
        c=min(b,h)
        if mode=='column':
            a.add('cache'+str(i),32*((1<<(c+1))-1))
            a.add('checkpoint_dfs',32*(h+1));a.drop('checkpoint_dfs')
            work+=n-1;leaves+=n
        for d in range(1,h+1):
            w=1<<d
            for j in range(4):a.add('fold'+str(j),16*(w//2))
            if d>c:
                a.add('layer_dfs',32*(h-d+1));a.drop('layer_dfs')
                work+=n-w;leaves+=n
            else:copies+=2*w
            # All factor tables have fixed per-round capacity, die before next.
            for t in range(d-1):
                z=eq_slots(d-1-t);entries+=z
                a.add('eq_factors',16*z);a.drop('eq_factors')
            for j in range(4):a.drop('fold'+str(j))
        if mode=='column':a.drop('cache'+str(i))
    pair_visits=sum(n-1-h for n,h in zip(sizes,hs))
    return dict(mode=mode,cached_depth=b,modeled_peak_bytes=a.peak,tree_internal_nodes=work,
        tree_work_ratio=work/(sum(sizes)-1),leaf_generations=leaves,leaf_ratio=leaves/sum(sizes),
        checkpoint_scalar_copies=copies,fold_scalar_updates=sum(4*(n-1-h) for n,h in zip(sizes,hs)),
        eq_factor_table_entries=entries,eq_common_weight_products=2*pair_visits,
        eq_sample_factor_products=4*pair_visits,events=a.events,new_mask_claim_PCS_sites=None)
